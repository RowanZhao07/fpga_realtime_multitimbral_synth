"""Original Nocturne study: 24 bars / 192 events, no recorded audio.

Eight eighth-note events per bar; alternating registers, rests and chord endings.
The checked-in text score is also accepted by serial_control.py --score.
"""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
CHORDS=[(60,64,67),(57,60,64),(53,57,60),(55,59,62),
        (62,65,69),(57,60,64),(53,57,60),(55,59,62),
        (64,67,71),(57,60,64),(62,65,69),(59,63,66),
        (60,64,67),(57,60,64),(53,57,60),(55,59,62),
        (62,65,69),(64,67,71),(53,57,60),(55,59,62),
        (60,64,67),(53,57,60),(55,59,62),(60,64,67)]
SEMITONES=[0,2,4,5,7,9,11,12,1,3,6,8,10]
NAMES=['C','C#','D','D#','E','F','F#','G','G#','A','A#','B']

def encode(notes):
    if not notes:return 1,0
    for bank in reversed(range(4)):
        base=48+bank*12
        if all(n-base in SEMITONES for n in notes):
            return bank,sum(1<<SEMITONES.index(n-base) for n in notes)
    raise ValueError(f'Chord cannot fit a physical octave: {notes}')

def main():
    events=[];text=['# Original Nocturne / 夜航练习曲 — 24 bars, 192 eighth-note events.','# Note format: C4:2 (two sixteenths), C4+E4+G4:2, REST:2.']
    for bar,chord in enumerate(CHORDS):
        shift=(-12 if bar<8 else 12 if bar<12 else 24 if bar<16 else 0)
        c=[n+shift if n+shift>=48 else n+shift+12 for n in chord]
        chord_base=(min(c)//12)*12
        inversion=[chord_base+n%12 for n in c]
        seq=[[c[0]],[c[1]],[c[2]],[c[1]],[c[0]+12],[c[2]],[c[1]],inversion if bar%4==3 else []]
        # Start at C4, then descend into the lower-register opening figure.
        if bar==0:seq[0]=[60]
        line=[]
        for notes in seq:
            bank,mask=encode(notes);events.append((1<<23)|(2<<15)|(bank<<13)|mask)
            line.append(('+'.join(NAMES[n%12]+str(n//12-1) for n in notes) if notes else 'REST')+':2')
        text.append(' '.join(line))
    lines=['`timescale 1ns/1ps','// Generated by tools/generate_guide.py; original composition, note events only.',
           'module guide_score_rom(input wire [8:0] address,output wire [23:0] event_word);',
           'function [23:0] lookup; input [8:0] index; begin case(index)']
    lines += [f"9'd{i}:lookup=24'h{w:06x};" for i,w in enumerate(events)]
    lines += ["default:lookup=24'h812000;",'endcase end endfunction','assign event_word=lookup(address);','endmodule','']
    (ROOT/'instrument/src/guide_score_rom.v').write_text('\n'.join(lines),encoding='utf-8')
    folder=ROOT/'assets/scores';folder.mkdir(exist_ok=True)
    (folder/'nocturne.txt').write_text('\n'.join(text)+'\n',encoding='utf-8')
    print(f'Generated {len(events)} events, octave banks {sorted(set((w>>13)&3 for w in events))}')

if __name__=='__main__':main()
