"""Yu Jian selected vocal passage from the user-provided numbered score.
G major, one pass: Yin tian bang wan che chuang wai -> na zhe ai de hao ma pai.
Built-in events are untimed; the player supplies rhythm. Ties merge, rests omit.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OFFSETS = [0,2,4,5,7,9,11,12,1,3,6,8,10]
DEGREES = [0,2,4,5,7,9,11]
NAMES = ['C','C#','D','D#','E','F','F#','G','G#','A','A#','B']
BPM = 93
VOCAL_BARS = '''
3:4 5:2 2:2~ 2:4 3:2 2:2~
2:2 1:2~ 1:8 1:2 7-:2
6-:2 7-:2 1:2 7-:2~ 7-:2 1:2~ 1:2 2:2
3:12 5:2 3:2~
3:4 5:2 2+:2~ 2+:4 1+:2 7:2~
7:2 1+:2~ 1+:8 1:2 7-:2
6-:2 7-:2 1:2 7-:2~ 7-:2 1:2~ 1:2 2:2
1:8 0:2 5:2 6:2 7:2
1+:4 7:2 1+:2 7:2 6:2 5:2 6:2~
6:2 5:2~ 5:2~ 5:2 1:4 2:2 3:2
4:4 3:2 4:2 5:2 1:2 2:2 3:2~
3:2 3:2~ 3:2 0:2 5:2 6:2 7:4
1+:4 7:2 1+:2 2+:2 1+:2 2+:2 3+:2~
3+:2 5:2~ 5:2~ 5:2 1:4 2:2 3:2
4:4 3:2 4:2 3:2 2:2~ 2:2 1:2
'''

def score_events():
    events = []; tied = False; sections = []
    def append(label, text, tonic, bar_units=16):
        nonlocal tied
        sections.append((label,len(events)-int(tied)))
        for bar,row in enumerate(text.strip().splitlines(),1):
            total = 0
            for token in row.split():
                match = re.fullmatch(r'(#?)([0-7])([+-]?):(\d+)(~?)',token)
                if not match: raise ValueError(token)
                sharp,degree,register,duration,tie = match.groups()
                duration = int(duration); total += duration
                pitch = None if degree=='0' else tonic+DEGREES[int(degree)-1]+bool(sharp)+{'':0,'+':12,'-':-12}[register]
                if pitch is not None and not 48<=pitch<=96: raise ValueError((label,bar,pitch))
                if tied:
                    if pitch is None or events[-1][0]!=pitch: raise ValueError(('invalid tie',label,bar,token))
                    events[-1]=(pitch,events[-1][1]+duration)
                else: events.append((pitch,duration))
                tied=bool(tie)
            if total!=bar_units: raise ValueError((label,bar,'bar duration',total))
    append('Yin tian pickup','5:2 3:2~',67,4)
    append('Yin tian to hao, one pass',VOCAL_BARS,67)
    append('Ma pai ending','7-:2 1:2~ 1:8',67,12)
    # Free note-on practice: the player supplies phrasing, with no rest timers.
    events=[(pitch,duration) for pitch,duration in events if pitch is not None]
    sections=[('Yin tian bang wan che chuang wai -> na zhe ai de hao ma pai',0)]
    assert not tied and len(events)<=512
    return events,sections

def encode(events):
    words=[];bank=1
    for pitch,duration in events:
        mask=0
        if pitch is not None:
            candidates=[b for b in range(4) if pitch-(48+12*b) in OFFSETS]
            bank=min(candidates,key=lambda b:(abs(b-bank),b))
            mask=1<<OFFSETS.index(pitch-(48+12*bank))
        words.append((duration<<15)|(bank<<13)|mask)
    return words

def main():
    events,sections=score_events();words=encode(events)
    text=['# 遇见 / Yu Jian — selected vocal passage, G major.',
          '# 阴天傍晚车窗外 -> 拿着爱的号码牌; one pass, no introduction/interlude/repeat.',
          '# Built-in GUIDE advances on each correct note-on; ends at DONE.',
          '# Tied notes merged; rests omitted. Durations retained for optional timed UART upload.']
    starts={i:label for label,i in sections}
    for i,(pitch,duration) in enumerate(events):
        if i in starts:text.append('# '+starts[i])
        text.append((NAMES[pitch%12]+str(pitch//12-1) if pitch is not None else 'REST')+f':{duration}')
    (ROOT/'assets/scores/yujian.txt').write_text('\n'.join(text)+'\n',encoding='utf-8')
    lines=['`timescale 1ns/1ps','// Generated by tools/generate_guide.py from the user-provided Yu Jian score.',
           'module guide_score_rom(input wire [8:0] address,output wire [23:0] event_word,',
           ' output wire [9:0] length);',f"assign length=10'd{len(words)};",
           'function [23:0] lookup; input [8:0] index; begin case(index)']
    lines += [f"9'd{i}:lookup=24'h{w:06x};" for i,w in enumerate(words)]
    lines += ["default:lookup=24'h000000;",'endcase end endfunction','assign event_word=lookup(address);','endmodule','']
    (ROOT/'instrument/src/guide_score_rom.v').write_text('\n'.join(lines),encoding='utf-8')
    print(f'{len(events)} events; {sum(d for _,d in events)} sixteenths; MIDI {min(n for n,_ in events if n is not None)}..{max(n for n,_ in events if n is not None)}; {BPM} BPM')
    for label,start in sections:print(start,label)

if __name__=='__main__':main()
