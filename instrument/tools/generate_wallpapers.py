"""Compile the existing eight wallpapers into bounded, self-contained Gowin ROMs.

160x120, 16 colours/image, four indices per 18-bit word. 38 image BSRAMs
and one palette BSRAM; no external files are needed when loading the .fs.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
W, H = 160, 120


def primitive(name, words, width, address, enable="1'b1"):
    depth = 18432 // width if width == 18 else 512
    per_init = 16 if width == 18 else 8
    init_width = 288 if width == 18 else 256
    words = list(words) + [0] * (depth - len(words))
    params = [f".READ_MODE(1'b0)", f".BIT_WIDTH({width})"]
    for i in range(64):
        value = sum(words[i * per_init + j] << (j * width) for j in range(per_init))
        params.append(f".INIT_RAM_{i:02X}({init_width}'h{value:0{init_width // 4}X})")
    cell = 'pROMX9' if width == 18 else 'pROM'
    return f"    {cell} #(\n        " + ",\n        ".join(params) + (
        f"\n    ) {name}(.DO({name}_data), .AD({address}), .CLK(clk),"
        f" .CE({enable}), .OCE(1'b1), .RESET(1'b0));\n")


def main():
    indices, palette, sources = [], [], []
    preview = ROOT / 'outputs/ui-20261101/wallpapers'
    preview.mkdir(parents=True, exist_ok=True)
    for n in range(1, 9):
        path = ROOT / f'assets/wallpapers/{n}.jpg'
        # Cover crop preserves geometry. Quantization is done offline, never in RTL.
        small = ImageOps.fit(Image.open(path).convert('RGB'), (W, H), Image.Resampling.LANCZOS)
        indexed = small.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        indices.extend(indexed.get_flattened_data())
        p = indexed.getpalette()
        palette.extend((p[i*3] << 16) | (p[i*3+1] << 8) | p[i*3+2] for i in range(16))
        indexed.convert('RGB').resize((800, 600), Image.Resampling.NEAREST).save(preview / f'{n}.png')
        sources.append({'path':str(path.relative_to(ROOT)), 'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
    words = [sum(indices[i+j] << (4*j) for j in range(4)) for i in range(0,len(indices),4)]
    pages = (len(words)+1023)//1024
    out = [f'''`timescale 1ns/1ps
// Generated by tools/generate_wallpapers.py. {pages}+1 BSRAMs, two-clock read.
module wallpaper_rom(input wire clk, input wire [15:0] address,
    input wire [1:0] slot, input wire [2:0] image_index,
    output wire [23:0] rgb);
    reg [5:0] page_d=0; reg [1:0] slot_d=0; reg [2:0] image_d=0;
    always @(posedge clk) begin page_d<=address[15:10];slot_d<=slot;image_d<=image_index;end
''']
    for i in range(pages):
        out.append(f'    wire [35:0] image_{i}_data;\n')
        out.append(primitive(f'image_{i}', words[i*1024:(i+1)*1024], 18,
                             "{address[9:0],4'b0}", f"address[15:10]==6'd{i}"))
    # OR gating maps to a balanced mux, instead of a wide serial priority chain.
    out.append('    wire [15:0] packed_indices =\n' + ' |\n'.join(
        f"        ({{16{{page_d==6'd{i}}}}} & image_{i}_data[15:0])" for i in range(pages)) + ';\n')
    out.append('    wire [3:0] colour_index=packed_indices >> {slot_d,2\'b00};\n')
    out.append('    wire [31:0] colours_data;\n')
    out.append(primitive('colours', palette, 32, "{2'b0,image_d,colour_index,5'b0}"))
    out.append('    assign rgb=colours_data[23:0];\nendmodule\n')
    (ROOT/'instrument/src/wallpaper_rom.v').write_text(''.join(out), encoding='utf-8')
    (preview/'expected.hex').write_text(''.join(f'{palette[(i//(W*H))*16+v]:06x}\n' for i,v in enumerate(indices)))
    (ROOT/'assets/wallpapers/rom_manifest.json').write_text(json.dumps({
        'size':[W,H], 'colours_per_image':16, 'image_blocks':pages, 'palette_blocks':1,
        'sources':sources}, indent=2)+'\n', encoding='utf-8')
    print(f'Generated {pages}+1 BSRAMs, {len(indices)} indexed pixels; eight wallpapers retained.')


if __name__ == '__main__':
    main()
