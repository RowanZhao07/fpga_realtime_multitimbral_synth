"""Pack the eight source JPGs into initialized GW5A FPGA wallpaper ROMs.

192x144, 64 colours/image, three 6-bit indices per 18-bit BSRAM word.
Only Pillow is required. Generated Verilog embeds the data so IDE and XSim
builds do not depend on a working-directory-specific $readmemh path.
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
WIDTH, HEIGHT, COLOURS = 192, 144, 64


def main():
    words, palette = [], []
    for number in range(1, 9):
        with Image.open(ROOT / "assets/wallpapers" / f"{number}.jpg") as source:
            fitted = ImageOps.fit(ImageOps.exif_transpose(source).convert("RGB"),
                                  (WIDTH, HEIGHT), Image.Resampling.LANCZOS)
        indexed = fitted.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT,
                                  dither=Image.Dither.NONE)
        indices = list(indexed.tobytes())
        words.extend(indices[i] | (indices[i+1] << 6) | (indices[i+2] << 12)
                     for i in range(0, len(indices), 3))
        colours = indexed.getpalette()[:COLOURS * 3]
        palette.extend((colours[i] << 16) | (colours[i+1] << 8) | colours[i+2]
                       for i in range(0, len(colours), 3))
    assert len(words) == 73728 and len(palette) == 512
    output = ROOT / "instrument/src/wallpaper_rom.v"
    with output.open("w", encoding="ascii", newline="\n") as f:
        f.write('''`timescale 1ns/1ps
// Generated by tools/generate_wallpapers.py from assets/wallpapers/1.jpg ... 8.jpg.
// 72 x 18K image blocks + one 512x24 palette block; two clock read latency.
module wallpaper_rom(input wire clk, input wire [16:0] address,
    input wire [1:0] slot, input wire [2:0] image_index,
    output wire [23:0] rgb);
    wire [35:0] page_data [0:71];
    wire [31:0] palette_data;
    reg [6:0] page_d=0;
    wire [17:0] packed_pixel=page_data[page_d][17:0];
    reg [1:0] slot_d=0;
    reg [2:0] image_d=0;
    wire [5:0] colour_index=slot_d==0 ? packed_pixel[5:0] :
                            slot_d==1 ? packed_pixel[11:6] : packed_pixel[17:12];
    always @(posedge clk) begin
        page_d<=address[16:10]; slot_d<=slot; image_d<=image_index;
    end
    assign rgb=palette_data[23:0];
    // Explicit X9 primitives use all 18 bits (inference otherwise selects
    // 16K x 1-bit ROMs, wasting parity bits and spilling other RAM into LUTs).
''')
        for page in range(72):
            f.write("    pROMX9 #(.READ_MODE(1'b0), .BIT_WIDTH(18),\n")
            for chunk in range(64):
                offset = page*1024 + chunk*16
                bits = sum(words[offset+i] << (i*18) for i in range(16))
                comma = "," if chunk < 63 else ""
                f.write(f"        .INIT_RAM_{chunk:02X}(288'h{bits:072X}){comma}\n")
            f.write(f"    ) image_page_{page}(.DO(page_data[{page}]), .AD({{address[9:0],4'b0}}),\n"
                    f"        .CLK(clk), .CE(address[16:10]==7'd{page}), .OCE(1'b1), .RESET(1'b0));\n")
        f.write("    pROM #(.READ_MODE(1'b0), .BIT_WIDTH(32),\n")
        for chunk in range(64):
            bits = sum(palette[chunk*8+i] << (i*32) for i in range(8))
            comma = "," if chunk < 63 else ""
            f.write(f"        .INIT_RAM_{chunk:02X}(256'h{bits:064X}){comma}\n")
        f.write("    ) colours(.DO(palette_data), .AD({image_d,colour_index,5'b0}),\n"
                "        .CLK(clk), .CE(1'b1), .OCE(1'b1), .RESET(1'b0));\nendmodule\n")
    print(f"Generated {output}: 8 wallpapers, 192x144, 64 colours, 73 BSRAM blocks")


if __name__ == "__main__":
    main()
